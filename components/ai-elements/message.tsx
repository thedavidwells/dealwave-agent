export type MessageResponseProps = ComponentProps<typeof Streamdown>;

const streamdownPlugins = { cjk, code, math, mermaid };

// Whitelist internal (relative path) and same-origin links. By default
// Streamdown wraps every link with an "external website" safety modal,
// which is wrong for links to our own routes (e.g. /deals/[id]). The
// modal also injects a <div> inside a <p>, producing hydration warnings.
const linkSafety = {
  enabled: true,
  onLinkCheck: (url: string): boolean => {
    // Relative URLs (e.g. "/deals/abc") are always our own routes.
    if (url.startsWith("/") && !url.startsWith("//")) return true;
    // Same-origin absolute URLs are trusted; everything else gets the
    // safety modal. Falls back to "external" when window isn't defined
    // (SSR pass) — safer to prompt than to silently allow.
    if (typeof window !== "undefined") {
      try {
        return new URL(url).origin === window.location.origin;
      } catch {
        return false;
      }
    }
    return false;
  },
};

// Override Streamdown's default <a> rendering so internal links
// (e.g. /deals/abc) open in a NEW TAB instead of replacing the chat
// session via same-tab navigation. useChat state lives in memory only;
// once the user navigates away, going Back returns to an empty
// conversation. Opening internal links in a new tab preserves the
// active chat indefinitely while the user inspects the saved deal.
//
// rel="noopener noreferrer" is mandatory whenever target="_blank":
// without it, the opened tab gets a window.opener reference back to
// the analyst tab, which is a tabnabbing vector.
// Shared link styling — underlined, blue-accent matching the design
// system. Streamdown's default <a> rendering doesn't underline links,
// which makes "View this deal →" (and any other markdown link the model
// emits) read as plain text instead of a clickable affordance.
const linkClassName =
  "underline underline-offset-2 transition-opacity hover:opacity-80";
const linkStyle = {
  color: "var(--dw-blue)",
  textDecorationColor: "var(--dw-blue)",
  textDecorationThickness: 1,
} as const;

const streamdownComponents = {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  a: ({ href, children, className, style, ...rest }: any) => {
    const isInternal =
      typeof href === "string" &&
      href.startsWith("/") &&
      !href.startsWith("//");
    // Merge our default link styling with anything the renderer or
    // markdown plugin may have passed through. Caller-provided styles
    // win — we're just setting the floor.
    const mergedClassName = cn(linkClassName, className);
    const mergedStyle = { ...linkStyle, ...(style ?? {}) };
    if (isInternal) {
      return (
        <a
          href={href}
          target="_blank"
          rel="noopener noreferrer"
          className={mergedClassName}
          style={mergedStyle}
          {...rest}
        >
          {children}
        </a>
      );
    }
    return (
      <a
        href={href}
        className={mergedClassName}
        style={mergedStyle}
        {...rest}
      >
        {children}
      </a>
    );
  },
};

export const MessageResponse = memo(
  ({ className, ...props }: MessageResponseProps) => (
    <Streamdown
      className={cn(
        "size-full [&>*:first-child]:mt-0 [&>*:last-child]:mb-0",
        className
      )}
      plugins={streamdownPlugins}
      linkSafety={linkSafety}
      components={streamdownComponents}
      {...props}
    />
  ),
  (prevProps, nextProps) =>
    prevProps.children === nextProps.children &&
    nextProps.isAnimating === prevProps.isAnimating
);

MessageResponse.displayName = "MessageResponse";

